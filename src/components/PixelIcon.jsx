export function PixelIcon({ name, size = 24 }) {
  const rows = ICONS[name];
  if (!rows) return null;

  const cells = [];
  rows.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === '#') cells.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    });
  });

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {cells}
    </svg>
  );
}
